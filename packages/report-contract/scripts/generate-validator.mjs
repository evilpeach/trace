#!/usr/bin/env node
// Ajv's compiler executes only here, never in the CSP-restricted application.
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const packageDirectory = fileURLToPath(new URL('..', import.meta.url));
const schemaUrl = new URL('../../../docs/trace/skills/trace-report/references/schema.json', import.meta.url);
const outputUrl = new URL('../src/generated/structural-validator.js', import.meta.url);
const schemaText = await readFile(schemaUrl, 'utf8');
const hash = createHash('sha256').update(schemaText).digest('hex');

if (process.argv.includes('--check')) {
  let generated = '';
  try { generated = await readFile(outputUrl, 'utf8'); } catch { /* Report one useful recovery command below. */ }
  if (!generated.includes(`export const SCHEMA_SHA256 = "${hash}";`)) {
    console.error('Trace structural validator is missing or stale. Run npm run generate-validator --workspace @trace/report-contract.');
    process.exitCode = 1;
  } else if (/\bnew\s+Function\b|\beval\s*\(/.test(generated)) {
    console.error('Trace structural validator contains CSP-unsafe runtime code generation.');
    process.exitCode = 1;
  } else {
    console.log(`Trace structural validator matches schema ${hash.slice(0, 12)} and contains no runtime code generation.`);
  }
} else {
  const [{ default: Ajv2020 }, { default: addFormats }, { default: standaloneCode }, { _ }, { build }] = await Promise.all([
    import('ajv/dist/2020.js'), import('ajv-formats'), import('ajv/dist/standalone/index.js'),
    import('ajv/dist/compile/codegen/index.js'), import('esbuild'),
  ]);
  const ajv = new Ajv2020({
    allErrors: false, strict: false, ownProperties: true,
    // Use this Ajv installation's Code instance. Workspaces may hoist
    // ajv-formats beside another Ajv version with an incompatible Code class.
    code: { source: true, lines: true, formats: _`require("ajv-formats/dist/formats").fullFormats` },
  });
  addFormats(ajv, { keywords: false });
  const validate = ajv.compile(JSON.parse(schemaText));
  const generated = standaloneCode(ajv, validate);
  // Standalone Ajv can reference small CommonJS runtime helpers. Bundle those
  // at generation time into a self-contained ESM module, without its compiler.
  const result = await build({
    absWorkingDir: packageDirectory,
    stdin: { contents: generated, resolveDir: packageDirectory, sourcefile: 'trace-structural-validator.cjs', loader: 'js' },
    bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
    write: false, legalComments: 'none',
  });
  const artifact = `// GENERATED by scripts/generate-validator.mjs. Do not edit.\n// Canonical schema SHA-256: ${hash}\nexport const SCHEMA_SHA256 = "${hash}";\n${result.outputFiles[0].text}`;
  if (/\bnew\s+Function\b|\beval\s*\(/.test(artifact)) throw new Error('Generated validator unexpectedly requires runtime code generation.');
  await mkdir(new URL('../src/generated/', import.meta.url), { recursive: true });
  await writeFile(outputUrl, artifact);
  console.log(`Generated CSP-safe Trace validator for schema ${hash.slice(0, 12)} (${Buffer.byteLength(artifact)} bytes).`);
}
